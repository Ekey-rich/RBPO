-- 5 связанных таблиц с ограничениями целостности.
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL CHECK (LENGTH(TRIM(name)) > 0),
    completed_exams INT NOT NULL DEFAULT 0 CHECK (completed_exams >= 0)
);

CREATE TABLE IF NOT EXISTS exams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL CHECK (LENGTH(TRIM(name)) > 0),
    passing_score INT NOT NULL CHECK (passing_score >= 0),
    time_limit_minutes INT NOT NULL CHECK (time_limit_minutes > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED'))
);

CREATE TABLE IF NOT EXISTS exam_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id BIGINT NOT NULL REFERENCES exams(id),
    question VARCHAR(500) NOT NULL,
    correct_answer VARCHAR(250) NOT NULL,
    max_score INT NOT NULL CHECK (max_score > 0)
);

CREATE TABLE IF NOT EXISTS exam_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id BIGINT NOT NULL REFERENCES exams(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS',
    started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMP,
    total_score INT NOT NULL DEFAULT 0 CHECK (total_score >= 0),
    UNIQUE (exam_id, user_id),
    CHECK ((status = 'IN_PROGRESS' AND finished_at IS NULL)
        OR (status = 'COMPLETED' AND finished_at IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS task_solutions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id BIGINT NOT NULL REFERENCES exam_attempts(id),
    task_id BIGINT NOT NULL REFERENCES exam_tasks(id),
    answer VARCHAR(250) NOT NULL,
    points INT NOT NULL DEFAULT 0 CHECK (points >= 0),
    UNIQUE (attempt_id, task_id)
);
